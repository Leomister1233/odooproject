PORTAL_TRANSLATIONS = {
    language_code: _normalize_translation_map(translations)
    for language_code, translations in PORTAL_TRANSLATIONS.items()
}


def get_portal_language(request=None):
    if request is None:
        return PORTAL_LANGUAGE_DEFAULT

    language = request.session.get("portal_language", PORTAL_LANGUAGE_DEFAULT)
    return language if language in PORTAL_LANGUAGE_CHOICES else PORTAL_LANGUAGE_DEFAULT


def translate_portal_text(value, language):
    if value is None:
        return ""

    text = str(value)
    if language == PORTAL_LANGUAGE_DEFAULT:
        return text

    return PORTAL_TRANSLATIONS.get(language, {}).get(text, text)


def build_toggle_language_url(path):
    query = urlencode({"next": path})
    return f"/language/toggle/?{query}"


def build_set_language_url(path, language_code):
    query = urlencode({"next": path})
    return f"/language/set/{language_code}/?{query}"
