def _fix_mojibake(value):
    if not isinstance(value, str):
        return value

    if "Ã" not in value and "â" not in value and "ð" not in value:
        return value

    try:
        return value.encode("latin-1").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return value


def _normalize_translation_map(values):
    normalized = {}
    for key, value in values.items():
        repaired = value
        for _ in range(3):
            candidate = _fix_mojibake(repaired)
            if candidate == repaired:
                break
            repaired = candidate
        normalized[key] = repaired
    return normalized

